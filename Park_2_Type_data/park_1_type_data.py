# Type Data Integer
a = 10 
print("Tipe data integer : {0}".format(a))
# Float
b = 3.14
print("Tipe data float : {0}".format(b))
# Complex
c = 2 + 3j
print("Tipe data Complex : {0}".format(c))

# sequensial type
# list
d = [1,2,3,4,5]
print("Tipe data list : {0}".format(d))
# tuple
e = (1,2,3,4,5)
print("Tipe data tuple : {0}".format(e))
# range
# range (start , end , step)
# range (end)
f = range(6)
print("Tipe data range : {0}".format(f))

# mapping type
# dictionary
g = {"nama" : "Alfadjri", "umur" : 20}
print("Tipe data dictionary : {0}".format(g["nama"]))

# set type
# set
h = {1,2,3,4,5}
print("Tipe data set : {0}".format(h))
# frozenset
i = frozenset(h)
print("Tipe data frozenset : {0}".format(i))

# boolean type
# boolean Nilainya True (1) atau False (0)
j = True
print("Tipe data boolean : {0}".format(j))


# Char
huruf = 'A'
print("Tipe data char : {0}".format(huruf))
# String
k = "Alfadjri"
print("Tipe data string : {0}".format(k))

# Biner
l = 0b01000001
char = chr(l)
print("Tipe data biner : {0}".format(l))
print("Karakter dari biner : {0}".format(char))